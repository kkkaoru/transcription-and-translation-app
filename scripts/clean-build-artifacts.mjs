#!/usr/bin/env node

/**
 * Remove generated build outputs that are safe to recreate.
 *
 * Rust `target/` directories are handled by the optional `--prune-rust` mode.
 * A normal cleanup removes frontend/bundle and coverage outputs, while a build
 * cleanup also removes Cargo's disposable debug and release caches.  Current
 * release executables and runtime resources are retained so a cleanup never
 * removes the installed app's source artifacts.  Bun's `--compile` command
 * leaves a temporary Mach-O file in its current working directory, so only
 * root-level files with Bun's generated name shape are considered.
 */

import { execFileSync } from "node:child_process";
import { lstat, mkdir, readdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { homedir, tmpdir } from "node:os";
import { basename, dirname, join, parse, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const CLEANUP_LOCK_DIRECTORY = ".kotoba-build-cleanup.lock";
const CLEANUP_LOCK_TIMEOUT_MS = 30_000;
const CLEANUP_LOCK_RETRY_MS = 100;
const CLEANUP_LOCK_STALE_MS = CLEANUP_LOCK_TIMEOUT_MS;

// Bun currently uses a hidden hexadecimal prefix and hexadecimal suffix for
// these temporary compile outputs.  Keep this root-level and suffix-limited so
// unrelated hidden files can never be selected by a broad glob.
const bunCompileOutput = /^\.[0-9a-f]{16}-[0-9a-f]{8}\.bun-build$/i;

const isWithin = (parent, child) => {
  const childRelative = relative(parent, child);
  return (
    childRelative.length > 0 &&
    childRelative !== ".." &&
    !childRelative.startsWith(`..${sep}`) &&
    !childRelative.startsWith(sep)
  );
};

const isAllowedRoot = (root) => {
  if (root === repositoryRoot) return true;
  const temporaryRoot = resolve(tmpdir());
  return root !== temporaryRoot && isWithin(temporaryRoot, root);
};

const assertSafeRoot = async (root) => {
  const filesystemRoot = parse(root).root;
  if (root === filesystemRoot || root === resolve(homedir())) {
    throw new Error(`refusing to clean filesystem root: ${root}`);
  }
  if (!isAllowedRoot(root)) {
    throw new Error(`cleanup root must be the repository or a temporary test directory: ${root}`);
  }
  const rootStat = await lstat(root);
  if (rootStat.isSymbolicLink() || !rootStat.isDirectory()) {
    throw new Error(`cleanup root must be a real directory: ${root}`);
  }
};

/**
 * Outputs that are regenerated by their respective frontend/Tauri build.
 * Do not add a Rust `target` directory itself to this list.
 */
const generatedDirectories = [
  "apps/desktop/dist",
  "apps/azookey-compare/.next",
  "apps/inference-gateway/dist",
  "packages/inference-server-core/dist",
  "packages/parapper-asr/dist",
  "apps/desktop/src-tauri/target/debug/bundle",
  "apps/desktop/src-tauri/target/release/bundle",
  "packages/parapper-asr/src-tauri/target/debug/bundle",
  "packages/parapper-asr/src-tauri/target/release/bundle",
  "packages/parapper-asr/target/release/bundle",
  "packages/parapper-asr/target/x86_64-pc-windows-msvc/release/bundle",
];

// Vitest writes reports beneath each workspace package.  They are generated
// outputs rather than source/runtime resources, so remove stale reports before
// every build to keep local and CI runs from retaining unbounded old coverage.
const coverageDirectories = [
  "apps/desktop/coverage",
  "apps/azookey-compare/coverage",
  "apps/inference-gateway/coverage",
  "apps/cloudflare-worker-server/coverage",
  "packages/inference-server-core/coverage",
  "packages/parapper-asr/coverage",
];

// Debug artifacts are never distributed and can grow without bound because
// every changed Rust dependency/feature creates another hashed `deps` and
// incremental tree.  Library-only targets have no runtime files to retain.
const disposableRustTargets = [
  "apps/desktop/src-tauri/target/debug",
  "packages/azookey-wasm/target",
  "packages/parapper-asr/target/debug",
  "packages/parapper-asr/target/x86_64-pc-windows-msvc/debug",
  "packages/parapper-asr/src-tauri/target",
  "packages/azookey-rust/target",
  "packages/vibrato/core/target",
  "packages/vibrato/wasm/target",
  "submodules/Parapper-ASR/target",
];

// Keep release binaries, bundled sidecars, and downloaded runtime resources;
// remove only Cargo's rebuildable indexes/objects.  This makes repeated
// release builds bounded without forcing the distributed artifacts to be
// rebuilt just to run the cleanup command.
const releaseCacheDirectories = [
  "apps/desktop/src-tauri/target/release/build",
  "apps/desktop/src-tauri/target/release/deps",
  "apps/desktop/src-tauri/target/release/.fingerprint",
  "apps/desktop/src-tauri/target/release/incremental",
  "apps/desktop/src-tauri/target/release/examples",
  "packages/parapper-asr/target/release/build",
  "packages/parapper-asr/target/release/deps",
  "packages/parapper-asr/target/release/.fingerprint",
  "packages/parapper-asr/target/release/incremental",
  "packages/parapper-asr/target/release/examples",
  "packages/parapper-asr/target/x86_64-pc-windows-msvc/release/build",
  "packages/parapper-asr/target/x86_64-pc-windows-msvc/release/deps",
  "packages/parapper-asr/target/x86_64-pc-windows-msvc/release/.fingerprint",
  "packages/parapper-asr/target/x86_64-pc-windows-msvc/release/incremental",
  "packages/parapper-asr/target/x86_64-pc-windows-msvc/release/examples",
];

const relativePath = (root, absolutePath) => relative(root, absolutePath) || ".";

const sleep = (milliseconds) =>
  new Promise((resolveSleep) => {
    setTimeout(resolveSleep, milliseconds);
  });

const processIsAlive = (pid) => {
  if (!Number.isInteger(pid) || pid <= 0) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return error?.code === "EPERM";
  }
};

const readLockOwner = async (lockDirectory) => {
  try {
    const owner = await readFile(join(lockDirectory, "owner.json"), "utf8");
    return JSON.parse(owner);
  } catch {
    return null;
  }
};

/**
 * Serialize cleanup calls for the same worktree. A directory is used because
 * mkdir is atomic across the supported filesystems; an owner PID lets a later
 * invocation reclaim a lock left behind by a crashed process.
 */
const acquireCleanupLock = async (root) => {
  const lockDirectory = join(root, CLEANUP_LOCK_DIRECTORY);
  const deadline = Date.now() + CLEANUP_LOCK_TIMEOUT_MS;
  while (true) {
    try {
      await mkdir(lockDirectory);
      await writeFile(
        join(lockDirectory, "owner.json"),
        JSON.stringify({ pid: process.pid, startedAt: new Date().toISOString() }),
        "utf8",
      );
      return async () => {
        await rm(lockDirectory, { recursive: true, force: true });
      };
    } catch (error) {
      if (error?.code !== "EEXIST") throw error;
      const owner = await readLockOwner(lockDirectory);
      let stale = owner && !processIsAlive(Number(owner.pid));
      if (!owner) {
        try {
          stale = Date.now() - (await stat(lockDirectory)).mtimeMs >= CLEANUP_LOCK_STALE_MS;
        } catch {
          stale = false;
        }
      }
      if (stale) {
        const staleDirectory = `${lockDirectory}.stale-${process.pid}-${Date.now()}`;
        try {
          await rename(lockDirectory, staleDirectory);
          await rm(staleDirectory, { recursive: true, force: true });
        } catch (staleError) {
          if (staleError?.code !== "ENOENT") throw staleError;
        }
        continue;
      }
      if (Date.now() >= deadline) {
        throw new Error(`timed out waiting for build cleanup lock (${CLEANUP_LOCK_DIRECTORY})`);
      }
      await sleep(CLEANUP_LOCK_RETRY_MS);
    }
  }
};

const listProcessCommands = () => {
  try {
    return (
      process.platform === "win32"
        ? execFileSync(
            "powershell",
            [
              "-NoProfile",
              "-Command",
              "Get-CimInstance Win32_Process | ForEach-Object { $_.CommandLine }",
            ],
            { encoding: "utf8" },
          )
        : execFileSync("ps", ["-axo", "command="], { encoding: "utf8" })
    )
      .split("\n")
      .map((line) => line.trim())
      .filter((line) => line.length > 0);
  } catch {
    return [];
  }
};

const commandBelongsToRoot = (line, root) => {
  const rootMarker = basename(root);
  return line.includes(root) || line.includes(`${sep}${rootMarker}${sep}`);
};

/**
 * Return active Rust build commands for this exact worktree. Cargo/rustc
 * include the absolute target path in their command line on macOS/Linux; a
 * conservative empty result on Windows avoids false positives where tasklist
 * does not expose command lines.
 */
const activeRustProcesses = (root, commands = listProcessCommands()) => {
  const rustCommand = /(?:^|[\\/\s])(?:cargo|rustc|rustdoc)(?:\.exe)?(?:\s|$)/i;
  return commands.filter((line) => commandBelongsToRoot(line, root) && rustCommand.test(line));
};

/**
 * Generated app outputs that must stay intact while a matching local server is
 * still running. Desktop/Tauri cleanup otherwise deletes a live Next.js
 * `.next` tree mid-request and leaves the comparison UI serving 500s.
 */
const liveGeneratedDirectories = (root, commands = listProcessCommands()) => {
  const live = new Set();
  const nextCommand = /(?:^|[\\/\s])(?:next)(?:\.exe)?(?:\s|$)/i;
  const compareMarker = `${sep}apps${sep}azookey-compare${sep}`;
  for (const line of commands) {
    if (!commandBelongsToRoot(line, root)) continue;
    if (
      nextCommand.test(line) &&
      (line.includes(compareMarker) || line.includes("apps/azookey-compare"))
    ) {
      live.add("apps/azookey-compare/.next");
    }
  }
  return live;
};

/**
 * Remove stale generated outputs.
 *
 * @param {{root?: string, dryRun?: boolean, temporaryOnly?: boolean, pruneRust?: boolean, activeProcesses?: string[], processCommands?: string[]}} [options]
 * @returns {Promise<{removed: string[], skipped: string[]}>}
 */
export async function cleanBuildArtifacts(options = {}) {
  const root = resolve(options.root ?? repositoryRoot);
  const dryRun = options.dryRun === true;
  const temporaryOnly = options.temporaryOnly === true;
  const pruneRust = options.pruneRust === true;
  const removed = [];
  const skipped = [];

  await assertSafeRoot(root);
  const releaseLock = await acquireCleanupLock(root);

  try {
    const processCommands = options.processCommands ?? listProcessCommands();
    const activeProcesses = options.activeProcesses ?? activeRustProcesses(root, processCommands);
    if (activeProcesses.length > 0) {
      return {
        removed,
        skipped: [
          `build cleanup deferred while ${activeProcesses.length} Rust process(es) are active`,
        ],
      };
    }
    const preservedDirectories =
      options.preservedDirectories instanceof Set
        ? options.preservedDirectories
        : liveGeneratedDirectories(root, processCommands);
    let entries;
    try {
      entries = await readdir(root, { withFileTypes: true });
    } catch (error) {
      if (error?.code === "ENOENT") {
        return { removed, skipped };
      }
      throw error;
    }

    for (const entry of entries) {
      if (!entry.isFile() || !bunCompileOutput.test(entry.name)) continue;
      const output = join(root, entry.name);
      if (!dryRun) await rm(output, { force: true });
      removed.push(relativePath(root, output));
    }

    for (const directory of [...generatedDirectories, ...coverageDirectories]) {
      if (temporaryOnly) break;
      if (preservedDirectories.has(directory)) {
        skipped.push(`${directory} (live local server)`);
        continue;
      }
      const output = join(root, directory);
      let stat;
      try {
        stat = await lstat(output);
      } catch (error) {
        if (error?.code === "ENOENT") continue;
        throw error;
      }
      if (stat.isSymbolicLink() || !stat.isDirectory()) {
        skipped.push(directory);
        continue;
      }
      if (!dryRun) await rm(output, { recursive: true, force: true });
      removed.push(directory);
    }

    if (pruneRust && !temporaryOnly) {
      if (activeProcesses.length > 0) {
        skipped.push(
          `Rust cleanup deferred while ${activeProcesses.length} build process(es) are active`,
        );
      } else {
        for (const directory of [...disposableRustTargets, ...releaseCacheDirectories]) {
          const output = join(root, directory);
          let stat;
          try {
            stat = await lstat(output);
          } catch (error) {
            if (error?.code === "ENOENT") continue;
            throw error;
          }
          if (stat.isSymbolicLink() || !stat.isDirectory()) {
            skipped.push(directory);
            continue;
          }
          if (!dryRun) await rm(output, { recursive: true, force: true });
          removed.push(directory);
        }
      }
    }

    return { removed, skipped };
  } finally {
    await releaseLock();
  }
}

const parseCliOptions = (argv) => {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--dry-run") {
      options.dryRun = true;
      continue;
    }
    if (argument === "--temporary-only") {
      options.temporaryOnly = true;
      continue;
    }
    if (argument === "--prune-rust") {
      options.pruneRust = true;
      continue;
    }
    if (argument === "--root") {
      const value = argv[index + 1];
      if (!value || value.startsWith("--")) {
        throw new Error("--root requires a directory path");
      }
      options.root = value;
      index += 1;
      continue;
    }
    throw new Error(`unknown option: ${argument}`);
  }
  return options;
};

const isDirectInvocation =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectInvocation) {
  try {
    const options = parseCliOptions(process.argv.slice(2));
    const result = await cleanBuildArtifacts(options);
    for (const path of result.removed) {
      console.log(`${options.dryRun ? "would clean" : "cleaned"} ${path}`);
    }
    if (result.removed.length === 0) {
      console.log("no stale build artifacts found");
    }
  } catch (error) {
    console.error(
      `build cleanup failed: ${error instanceof Error ? error.message : String(error)}`,
    );
    process.exitCode = 1;
  }
}
